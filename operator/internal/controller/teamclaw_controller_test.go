// Unit tests for the TeamClaw reconciler (fake client, no envtest needed).
//
// Regression guards for #224 (incl. cross-review rework):
//   - the worker-pod List selector must match the labels the TS-side
//     KubernetesProvisioner stamps on worker pods (app/teamclaw.managed/
//     teamclaw.team/teamclaw.role) - NOT the operator's labelsFor set, which
//     only marks the controller objects. Matching the wrong set made
//     status.workerPods count the controller pod itself (恒 1) after the
//     first fix, and 恒 0 before it.
//   - sanitizeName must replicate the TS implementation character-for-character
//   - reconcileStatus counts worker pods and keeps previous counts on List
//     errors instead of silently reporting 0
//   - equalStatus must compare condition Messages so error text doesn't go stale
//   - reconcileDeployment must preserve third-party pod-template annotations
