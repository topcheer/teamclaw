func testScheme(t *testing.T) *runtime.Scheme {
	t.Helper()
	sch := runtime.NewScheme()
	if err := clientgoscheme.AddToScheme(sch); err != nil {
		t.Fatalf("clientgo scheme: %v", err)
	}
	if err := teav1.AddToScheme(sch); err != nil {
		t.Fatalf("teamclaw scheme: %v", err)
	}
	return sch
}

// TestSanitizeNameMatchesTSImpl pins the Go replica to outputs generated by
// running the TS implementation (src/src/controller/worker-provisioning.ts
// sanitizeName/sanitizePathSegment) directly. The inputs cover every branch:
// run collapsing (A__B), mixed legal/illegal runs (a - b -> a---b because "-"
// is legal), all-illegal fallback (worker), slice-at-max then re-trim, blank
// spec teamName via effectiveTeamName ("TeamClaw" -> teamclaw), and unicode.
func TestSanitizeNameMatchesTSImpl(t *testing.T) {
	cases := []struct {
		in   string
		want string
	}{
		{"Alpha Team!", "alpha-team"},
		{"A__B", "a-b"},
		{"a - b", "a---b"}, // space and "-" interleave: " "-"-""-" -> three dashes
		{"---", "worker"},  // all-illegal -> sanitizePathSegment fallback
		{"", "worker"},
		{"TeamClaw", "teamclaw"},
		{"UPPER-CASE-OK", "upper-case-ok"},
		{"demo-team", "demo-team"},
		{"team", "team"},
		{"-lead-trail-", "lead-trail"},
		{"a.b/c:d", "a-b-c-d"},
		{"xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx", "xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx"}, // 45 -> 40
		{"ab-ab-ab-ab-ab-ab-ab-ab-ab-ab-ab-", "ab-ab-ab-ab-ab-ab-ab-ab-ab-ab-ab"},                     // trailing dash after slice trim
		{"a-----------------------------------------b", "a"},                                          // slice(40) then re-trim eats the dash run
		{"team      x", "team-x"},
		{"中文 团队!Test", "test"}, // unicode collapses, leading "-" trimmed
		{"  demo-team  ", "demo-team"},
	}
	for _, tc := range cases {
		if got := sanitizeName(tc.in, 40); got != tc.want {
			t.Errorf("sanitizeName(%q, 40) = %q, want %q (TS output)", tc.in, got, tc.want)
		}
	}
	// effectiveTeamName mirrors the TS PluginConfig parse: trim, fallback
	// "TeamClaw" - so a blank spec.teamName lands on the same label value on
	// both sides ("teamclaw").
	if got := effectiveTeamName("  "); got != "TeamClaw" {
		t.Errorf("effectiveTeamName(blank) = %q, want TeamClaw", got)
	}
	if got := sanitizeName(effectiveTeamName(""), 40); got != "teamclaw" {
		t.Errorf("blank spec teamName -> label %q, want teamclaw", got)
	}
}

// workerLabels mirrors the TS KubernetesProvisioner pod manifest labels
// (worker-provisioning.ts metadata.labels).
func workerLabels(teamName, role string) map[string]string {
	return map[string]string{
		"app":              "teamclaw-worker",
		"teamclaw.managed": "true",
		"teamclaw.team":    sanitizeName(effectiveTeamName(teamName), 40),
		"teamclaw.role":    sanitizeName(role, 40),
	}
}

// TestWorkerPodSelectorMatchesWorkerLabels asserts the #224 invariant: the
// pod List selector matches the TS-stamped worker label set, and does NOT
// match the operator's own labelsFor set (controller objects) or other teams.
func TestWorkerPodSelectorMatchesWorkerLabels(t *testing.T) {
	tm := &teav1.TeamClaw{
		ObjectMeta: metav1.ObjectMeta{Name: "alpha", Namespace: "default"},
		Spec:       teav1.TeamClawSpec{TeamName: "Alpha Team!"},
	}
	selector := workerPodSelector(tm)
	if len(selector) != 2 {
		t.Fatalf("selector = %v, want managed+team pair", selector)
	}

	sel, err := metav1.LabelSelectorAsSelector(&metav1.LabelSelector{MatchLabels: selector})
	if err != nil {
		t.Fatalf("selector conversion: %v", err)
	}
	if !sel.Matches(klabels.Set(workerLabels(tm.Spec.TeamName, "coder"))) {
		t.Errorf("selector %v does not match real worker labels %v", selector, workerLabels(tm.Spec.TeamName, "coder"))
	}
	// Controller objects (labelsFor) must NOT be selected - counting them
	// made status.workerPods恒1 in the first fix attempt.
	if sel.Matches(klabels.Set(labelsFor(tm))) {
		t.Errorf("selector %v must not match operator labelsFor set %v (controller pod would be counted)", selector, labelsFor(tm))
	}
	// A different team's workers must not be selected.
	if sel.Matches(klabels.Set(workerLabels("Other Team", "coder"))) {
		t.Errorf("selector %v unexpectedly matches another team's worker labels", selector)
	}
	// Blank spec.teamName aligns both sides on "teamclaw".
	blank := &teav1.TeamClaw{ObjectMeta: metav1.ObjectMeta{Name: "b", Namespace: "default"}}
	blankSel, err := metav1.LabelSelectorAsSelector(&metav1.LabelSelector{MatchLabels: workerPodSelector(blank)})
	if err != nil {
		t.Fatalf("selector conversion: %v", err)
	}
	if !blankSel.Matches(klabels.Set(workerLabels("", "coder"))) {
		t.Error("blank teamName: selector does not match TS fallback label teamclaw.team=teamclaw")
	}
}

func newTestClient(t *testing.T, objs ...client.Object) client.WithWatch {
	t.Helper()
	return fake.NewClientBuilder().
		WithScheme(testScheme(t)).
		WithStatusSubresource(&teav1.TeamClaw{}).
		WithObjects(objs...).
		Build()
}

func podWithLabels(name, namespace string, labels map[string]string, phase corev1.PodPhase) *corev1.Pod {
	return &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: namespace, Labels: labels},
		Status:     corev1.PodStatus{Phase: phase},
	}
}

// TestReconcileStatusCountsWorkerPods: TS-stamped worker pods are counted;
// the controller pod (labelsFor), other teams, other namespaces are not.
func TestReconcileStatusCountsWorkerPods(t *testing.T) {
	tm := &teav1.TeamClaw{
		ObjectMeta: metav1.ObjectMeta{Name: "alpha", Namespace: "default"},
		Spec: teav1.TeamClawSpec{
			TeamName:   "Alpha Team",
			Controller: teav1.ControllerSpec{ModelConfigSecretRef: "alpha-config"},
		},
	}
	c := newTestClient(t, tm,
		podWithLabels("w1", "default", workerLabels(tm.Spec.TeamName, "coder"), corev1.PodRunning),
		podWithLabels("w2", "default", workerLabels(tm.Spec.TeamName, "reviewer"), corev1.PodPending),
		podWithLabels("w3", "default", workerLabels(tm.Spec.TeamName, "coder"), corev1.PodSucceeded), // not running/pending
		// The controller pod itself (operator labelsFor set): must NOT count.
		podWithLabels("alpha-controller-aaa", "default", labelsFor(tm), corev1.PodRunning),
		// Another team's workers: must NOT count.
		podWithLabels("w-other", "default", workerLabels("Beta Team", "coder"), corev1.PodRunning),
		// Same labels but another namespace: must NOT count.
		podWithLabels("w-elsewhere", "elsewhere", workerLabels(tm.Spec.TeamName, "coder"), corev1.PodRunning),
	)
	ctx := context.Background()

	var fresh teav1.TeamClaw
	if err := c.Get(ctx, types.NamespacedName{Namespace: "default", Name: "alpha"}, &fresh); err != nil {
		t.Fatalf("get teamclaw: %v", err)
	}
	r := &TeamClawReconciler{Client: c, Scheme: c.Scheme()}
	if err := r.reconcileStatus(ctx, &fresh); err != nil {
		t.Fatalf("reconcileStatus: %v", err)
	}

	var after teav1.TeamClaw
	if err := c.Get(ctx, types.NamespacedName{Namespace: "default", Name: "alpha"}, &after); err != nil {
		t.Fatalf("get after: %v", err)
	}
	if after.Status.WorkerPods.Running != 1 || after.Status.WorkerPods.Pending != 1 {
		t.Errorf("workerPods = running:%d pending:%d, want running:1 pending:1 (controller pod and other teams excluded)",
			after.Status.WorkerPods.Running, after.Status.WorkerPods.Pending)
	}
	if after.Status.ControllerEndpoint != "http://alpha-controller.default.svc" {
		t.Errorf("controllerEndpoint = %q", after.Status.ControllerEndpoint)
	}
	var ready *metav1.Condition
	for i := range after.Status.Conditions {
		if after.Status.Conditions[i].Type == "Ready" {
			ready = &after.Status.Conditions[i]
		}
	}
	if ready == nil || ready.Status != metav1.ConditionFalse {
		t.Errorf("Ready condition = %+v, want False (no deployment in fixture)", ready)
	}
}

// TestReconcileStatusKeepsCountsOnListError: a failing pod List must keep the
// previously observed counts, not silently report 0 (#224).
func TestReconcileStatusKeepsCountsOnListError(t *testing.T) {
	tm := &teav1.TeamClaw{
		ObjectMeta: metav1.ObjectMeta{Name: "alpha", Namespace: "default"},
		Spec: teav1.TeamClawSpec{
			TeamName:   "Alpha Team",
			Controller: teav1.ControllerSpec{ModelConfigSecretRef: "alpha-config"},
		},
		Status: teav1.TeamClawStatus{WorkerPods: teav1.WorkerPodsStatus{Running: 5, Pending: 2}},
	}
	c := fake.NewClientBuilder().
		WithScheme(testScheme(t)).
		WithStatusSubresource(&teav1.TeamClaw{}).
		WithObjects(tm).
		WithInterceptorFuncs(interceptor.Funcs{
			List: func(ctx context.Context, cl client.WithWatch, list client.ObjectList, opts ...client.ListOption) error {
				if _, ok := list.(*corev1.PodList); ok {
					return errors.New("api server unreachable")
				}
				return cl.List(ctx, list, opts...)
			},
		}).
		Build()
	ctx := context.Background()

	var fresh teav1.TeamClaw
	if err := c.Get(ctx, types.NamespacedName{Namespace: "default", Name: "alpha"}, &fresh); err != nil {
		t.Fatalf("get teamclaw: %v", err)
	}
	r := &TeamClawReconciler{Client: c, Scheme: c.Scheme()}
	if err := r.reconcileStatus(ctx, &fresh); err != nil {
		t.Fatalf("reconcileStatus: %v", err)
	}

	var after teav1.TeamClaw
	if err := c.Get(ctx, types.NamespacedName{Namespace: "default", Name: "alpha"}, &after); err != nil {
		t.Fatalf("get after: %v", err)
	}
	if after.Status.WorkerPods.Running != 5 || after.Status.WorkerPods.Pending != 2 {
		t.Errorf("workerPods = running:%d pending:%d, want preserved running:5 pending:2", after.Status.WorkerPods.Running, after.Status.WorkerPods.Pending)
	}
}

// TestEqualStatusComparesMessage: Message-only changes must produce unequal
// status so error messages don't go stale (#224 W3).
func TestEqualStatusComparesMessage(t *testing.T) {
	a := teav1.TeamClawStatus{Conditions: []metav1.Condition{{
		Type: "Ready", Status: metav1.ConditionFalse, Reason: "Progressing", Message: "config secret not found",
	}}}
	b := teav1.TeamClawStatus{Conditions: []metav1.Condition{{
		Type: "Ready", Status: metav1.ConditionFalse, Reason: "Progressing", Message: "deployment not ready",
	}}}
	if equalStatus(a, b) {
		t.Error("equalStatus ignored Message difference")
	}
	b.Conditions[0].Message = a.Conditions[0].Message
	if !equalStatus(a, b) {
		t.Error("equalStatus must treat identical status as equal")
	}
}

// TestReconcileDeploymentPreservesTemplateAnnotations: annotations injected on
// the pod template by third parties (webhook mutators) must survive a
// reconcile that rebuilds the template (#224 Info).
func TestReconcileDeploymentPreservesTemplateAnnotations(t *testing.T) {
	tm := &teav1.TeamClaw{
		ObjectMeta: metav1.ObjectMeta{Name: "alpha", Namespace: "default"},
		Spec: teav1.TeamClawSpec{
			TeamName:   "Alpha Team",
			Image:      "ghcr.io/topcheer/teamclaw-openclaw:latest",
			Controller: teav1.ControllerSpec{ModelConfigSecretRef: "alpha-config"},
		},
	}
	c := newTestClient(t, tm)
	ctx := context.Background()

	r := &TeamClawReconciler{Client: c, Scheme: c.Scheme()}
	if err := r.reconcileDeployment(ctx, tm); err != nil {
		t.Fatalf("first reconcileDeployment: %v", err)
	}

	// Simulate a mutating webhook stamping an annotation after creation.
	dep := &appsv1.Deployment{}
	key := types.NamespacedName{Namespace: "default", Name: "alpha-controller"}
	if err := c.Get(ctx, key, dep); err != nil {
		t.Fatalf("get deployment: %v", err)
	}
	dep.Spec.Template.Annotations = map[string]string{"vault.example.com/agent-inject": "true"}
	if err := c.Update(ctx, dep); err != nil {
		t.Fatalf("inject annotation: %v", err)
	}

	if err := r.reconcileDeployment(ctx, tm); err != nil {
		t.Fatalf("second reconcileDeployment: %v", err)
	}
	dep = &appsv1.Deployment{}
	if err := c.Get(ctx, key, dep); err != nil {
		t.Fatalf("get deployment after: %v", err)
	}
	if dep.Spec.Template.Annotations["vault.example.com/agent-inject"] != "true" {
		t.Errorf("third-party template annotation wiped by reconcile: %v", dep.Spec.Template.Annotations)
	}
	// No stray volumes: the unused "state" EmptyDir must stay gone (#224).
	for _, v := range dep.Spec.Template.Spec.Volumes {
		if v.Name == "state" {
			t.Errorf("unused state EmptyDir volume still present")
		}
	}
}
